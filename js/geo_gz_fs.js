  // 大图投影原点不同，既不能做 48 格平移也不能追加近似佛山要素，遇到 gzBig 直接跳过。
  const G = (CM.GEOS && CM.GEOS.gz1990) || (CM.GEOS && CM.GEOS.gz) || CM.GEO;
  if (!G || G.foshanExtended || G.gzBig) return;
  const DX = 48, CELL = 64;

  // ── 1. 平移既有地理数据 ────────────────────────────────────────────────
  // 增量编码的第一对坐标是相对原点 (0,0) 的差分，把它加上 DX*64 即整条折线右移 DX 格，
  // 其余差分链与名称索引原样保留，因此不丢失任何精度、不改变任何要素的引用关系。
  const readVar = function (s, i) {
    let r = 0, sh = 0, b, j = i;
    do { b = s.charCodeAt(j++) - 63; r |= (b & 31) << sh; sh += 5; } while (b >= 32);
    return [r, j];
  };
  const zig = function (r) { return (r & 1) ? ~(r >> 1) : (r >> 1); };
  const putVar = function (v) {
    let s = '', u = v < 0 ? ~(v << 1) : (v << 1);
    while (u >= 32) { s += String.fromCharCode((32 | (u & 31)) + 63); u >>>= 5; }
    return s + String.fromCharCode(u + 63);
  };
  const shift = function (s, from) {
    const a = readVar(s, from), b = readVar(s, a[1]);
    return s.slice(0, from) + putVar(zig(a[0]) + DX * CELL) + s.slice(a[1], b[1]) + s.slice(b[1]);
  };
  const shiftRings = function (row, first) {
    for (let k = first; k < row.length; k++) if (typeof row[k] === 'string') row[k] = shift(row[k], 1);
  };
