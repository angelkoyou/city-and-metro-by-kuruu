// 广佛同城扩展（地图第 3 版）：以广州 OSM 数据为基础，把整张图向东平移 48 格（12 km），
// 在原图西侧补入佛山中心城区（禅城、南海中东部与顺德北部），两地共用同一套格网与投影。
//
// 数据约定与 geo_gz.js 完全一致：坐标单位为 250 m 的游戏格，折线用 1/64 格精度的增量编码，
// 面要素首字符为环标记（'o'=外环），names 为全局名称表，places 为 [地名, x, y, 类型]。
// 广州原有的 OSM 要素一个都不改动，只在载入时平移其坐标；本文件追加的佛山要素沿用同样的字段与编码。
// 佛山部分的河道走向、主干路网与镇街界为按公开地理资料绘制的近似边界（非 OSM 精确拾取），
// 东端对齐原广州图西界上已有的白坭水道、水口水道、广佛河、佛山水道、平洲水道与潭洲水道，
// 保证水系与路网在 x = 48 的接缝处连续。
//
// v2.7.1：佛山不是「2010 年才突然出现的空地」。片区开放年份控制的是可建设权限，
