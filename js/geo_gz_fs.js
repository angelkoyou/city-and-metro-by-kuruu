  let seed = 20261110;
  const rnd = function () { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 4294967296; };
  const rr = function (a, b) { return a + (b - a) * rnd(); };
  const jit = function (a) { return (rnd() - 0.5) * (a == null ? 0.3 : a); };

